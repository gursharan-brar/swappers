/** A glyph as a 7-row list of 5-wide boolean rows. glyph[row][col] === true means solid. */
export type GlyphPattern = readonly (readonly boolean[])[];

function parse(char: string, raw: string): GlyphPattern {
  const rows = raw.trim().split(/\s+/);
  if (rows.length !== GLYPH_H) {
    throw new Error(`Glyph '${char}' has ${rows.length} rows, expected ${GLYPH_H}`);
  }
  return rows.map((row, r) => {
    if (row.length !== GLYPH_W) {
      throw new Error(`Glyph '${char}' row ${r} is '${row}', expected ${GLYPH_W} characters`);
    }
    return [...row].map((c) => c === '#');
  });
}

const GLYPHS: ReadonlyMap<string, GlyphPattern> = new Map(
  Object.entries(RAW).map(([char, raw]) => [char, parse(char, raw)]),
);

export function hasGlyph(char: string): boolean {
  return GLYPHS.has(char);
}

export function getGlyph(char: string): GlyphPattern {
  const glyph = GLYPHS.get(char);
  if (!glyph) throw new Error(`No glyph for '${char}'`);
  return glyph;
}

export function glyphChars(): string[] {
  return [...GLYPHS.keys()];
}
